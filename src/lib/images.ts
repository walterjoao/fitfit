export type ImageCategory = keyof typeof unsplashImages;

export function pickImage(category: ImageCategory, seed: number) {
  const arr = unsplashImages[category];
  return arr[seed % arr.length];
}

export function bgImage(url: string) {
  return `url(${url}) center/cover no-repeat`;
}
